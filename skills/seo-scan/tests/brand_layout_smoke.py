#!/usr/bin/env python3
"""Verify brand dimensions and inline footer layout in actual PDF engines."""
import argparse
import json
from pathlib import Path
from test_brand_layout import documents


def check_weasy(cases,artifacts):
    """Use optional engine layout boxes only in QA, never scanner/runtime logic."""
    from weasyprint import HTML
    try:
        from weasyprint import URLFetcher
        default_fetcher=URLFetcher()
    except ImportError:  # supported older optional WeasyPrint APIs
        from weasyprint import default_url_fetcher
        default_fetcher=default_url_fetcher
    requests=[]
    def inline_only(url,*args,**kwargs):
        requests.append(url.split(':',1)[0])
        assert url.startswith('data:'),'Controlled report requested a non-inline resource'
        return default_fetcher(url,*args,**kwargs)
    for name,output in cases:
        for hints in (False,True):
            doc=HTML(string=output,url_fetcher=inline_only).render(presentational_hints=hints)
            logos=[];credits=[]
            for index,page in enumerate(doc.pages):
                for box in page._page_box.descendants():
                    if (getattr(box,'element_tag',None)=='img' and type(box).__name__.endswith('ReplacedBox')
                            and box.element.get('class')=='brand-logo'):
                        logos.append((index,box.width,box.height,box.position_y))
                    if getattr(box,'text','').startswith('Generated by'):
                        credits.append((index,box.position_y,box.height))
            assert [(round(w,2),round(h,2)) for page,w,h,y in logos]==[(46,46),(16,16)],(name,hints,logos)
            assert len(credits)==1,(name,hints,credits)
            footer=logos[1];credit=credits[0]
            assert footer[0]==credit[0] and footer[3]<credit[1]+credit[2] and footer[3]+footer[2]>credit[1],(name,hints,footer,credit)
            pdf=doc.write_pdf()
            assert pdf.startswith(b'%PDF-')
            if artifacts:(artifacts/(name+'-weasy-'+str(hints)+'.pdf')).write_bytes(pdf)
    assert requests and set(requests)=={'data'},requests


def check_chromium(cases,artifacts):
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True)
        try:
            page=browser.new_page();requests=[]
            def deny(route):requests.append(route.request.url);route.abort()
            page.route('http://**/*',deny);page.route('https://**/*',deny)
            for name,output in cases:
                page.set_content(output)
                page.wait_for_function('Array.from(document.querySelectorAll("img.brand-logo")).every(n=>n.complete&&n.naturalWidth>0)')
                for media,width in [('screen',320),('screen',390),('screen',1100),('print',794)]:
                    page.emulate_media(media=media);page.set_viewport_size({'width':width,'height':1000})
                    sizes=page.locator('img.brand-logo').evaluate_all('(nodes)=>nodes.map(n=>({height:n.getBoundingClientRect().height,width:n.getBoundingClientRect().width}))')
                    assert sizes==[{'height':46,'width':46},{'height':16,'width':16}],(name,media,width,sizes)
                    inline=page.locator('.foot').evaluate('''n=>{
                        const image=n.querySelector('img').getBoundingClientRect();
                        const text=Array.from(n.childNodes).find(c=>c.nodeType===Node.TEXT_NODE&&c.textContent.includes('Generated by'));
                        const range=document.createRange();range.selectNodeContents(text);
                        const line=range.getClientRects()[0];
                        return image.top<line.bottom&&image.bottom>line.top;
                    }''')
                    assert inline,(name,media,width)
                    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),(name,media,width)
                    if artifacts and width==390:page.screenshot(path=str(artifacts/(name+'-390.png')),full_page=True)
                pdf=page.pdf(format='A4',print_background=True)
                assert pdf.startswith(b'%PDF-')
                if artifacts:(artifacts/(name+'-chromium.pdf')).write_bytes(pdf)
            assert not requests,requests
        finally:browser.close()


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--engine',choices=('both','chromium','weasyprint'),default='both')
    parser.add_argument('--artifacts',type=Path)
    parser.add_argument('--html',type=Path,action='append',default=[])
    args=parser.parse_args(argv)
    if args.artifacts:args.artifacts.mkdir(parents=True,exist_ok=True)
    cases=documents()+[('installed-'+str(i),path.read_text(encoding='utf-8')) for i,path in enumerate(args.html)]
    if args.engine in ('both','chromium'):check_chromium(cases,args.artifacts)
    if args.engine in ('both','weasyprint'):check_weasy(cases,args.artifacts)
    print(json.dumps({'engine':args.engine,'controlled_documents':len(cases),'header_css_px':46,'footer_css_px':16,
                      'footer_inline_with_credit':True,'external_requests':0,'measurement_not_SEO_outcome':True}))
    return 0


if __name__=='__main__':raise SystemExit(main())
