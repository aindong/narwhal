#!/usr/bin/env python3
"""Generate a starter ``/llms.txt`` for a site.

Seeds from the homepage (site name + description) and discovered pages (from the
sitemap or internal links), fetches each page's title/description, groups them
into sections, and emits an llms.txt-formatted markdown file (see llmstxt.org).

This is a *starting point* to curate, not a finished file — placeholders are
marked ``TODO``. Note: evidence that llms.txt affects AI-search visibility is
still limited; treat it as a low-cost, low-certainty addition (see
references/geo-llmo.md).

Usage:
    python generate_llms.py https://example.com
    python generate_llms.py https://example.com --max-pages 60 -o llms.txt
"""

from __future__ import annotations

import argparse
import os
import sys
from concurrent.futures import ThreadPoolExecutor
from urllib.parse import urljoin, urlparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from lib import http, htmlx  # noqa: E402
from lib import config as configlib  # noqa: E402
from lib.cli_errors import url_errors  # noqa: E402
from lib.markdown_text import table_text  # noqa: E402
from lib.robots import RobotsTxt  # noqa: E402
import crawl_site  # noqa: E402


class GenerationError(ValueError):
    """A generation precondition failed before an artifact could be produced."""


def _metadata_problem(resp):
    if not resp.ok:
        return 'failed_request'
    if http.has_range_evidence(resp):
        return 'partial_response'
    if resp.headers.get('x-narwhal-truncated') == 'true':
        return 'truncated_response'
    content_type = resp.headers.get('content-type', '').split(';', 1)[0].strip().lower()
    if content_type and content_type not in ('text/html', 'application/xhtml+xml'):
        return 'unsupported_content_type'
    if not resp.text.strip():
        return 'empty_body'
    return None


def _without_userinfo(url: str) -> str:
    """Remove authority credentials without rewriting path/query/fragment text."""
    authority = urlparse(url).netloc
    return url.replace(authority, authority.rsplit('@', 1)[-1], 1) if '@' in authority else url


def section_for(url: str) -> str:
    """Bucket a URL into an llms.txt section by its path."""
    path = urlparse(url).path.strip("/")
    if not path:
        return "Main"
    parts = path.split("/")
    if len(parts) == 1:  # top-level pages (/about, /contact) share "Main"
        return "Main"
    return parts[0].replace("-", " ").replace("_", " ").strip().title() or "Main"


def group_sections(pages: list) -> list:
    """Group page metas into ordered ``[(section, [pages])]`` (Main first)."""
    buckets: dict = {}
    for p in pages:
        buckets.setdefault(section_for(p["url"]), []).append(p)
    ordered = []
    if "Main" in buckets:
        ordered.append(("Main", buckets.pop("Main")))
    for name in sorted(buckets):
        ordered.append((name, buckets[name]))
    return ordered


def _slug_title(url: str) -> str:
    slug = urlparse(url).path.strip("/").split("/")[-1]
    return slug.replace("-", " ").replace("_", " ").title()


def _metadata_text(value: str) -> str:
    text = ''.join(' ' if ord(char) < 32 or ord(char) == 127 else char for char in (value or ''))
    text = table_text(' '.join(text.split())).replace('#', r'\#')
    return '\\' + text if text.startswith(('-', '+')) else text


def _link_destination(url: str) -> str:
    if any(char.isspace() or ord(char) < 32 or ord(char) == 127 for char in url):
        raise GenerationError('Candidate URLs cannot contain raw whitespace/control characters; supply an encoded URL.')
    return _without_userinfo(url).translate(str.maketrans({char: '\\' + char for char in '\\()<>&'}))


def render_llms_txt(site_name: str, description: str, sections: list, *, coverage=None) -> str:
    lines = [f"# {_metadata_text(site_name) or 'TODO: site name'}", ""]
    lines.append(f"> {_metadata_text(description) or 'TODO: one-sentence description of the site.'}")
    lines.append("")
    lines.append("<!-- Starter llms.txt generated by narwhal — review and curate "
                 "before publishing. Remove pages that are not key entry points. -->")
    lines.append("")
    if coverage and coverage.get('omitted_pages', 0):
        lines.append(f"<!-- Metadata coverage: {coverage['included_pages']} of "
                     f"{coverage['attempted_pages']} selected page fetches included; "
                     f"{coverage['omitted_pages']} omitted due to failed, partial/truncated, "
                     "empty or unsupported-content responses. Counts cover selected metadata "
                     "fetches, not the whole site. Review missing entries before publishing. -->")
        lines.append('')
    authentication_removed = (coverage or {}).get('authentication_removed') is True or any(
        _without_userinfo(page['url']) != page['url'] for _, pages in sections for page in pages)
    if authentication_removed:
        lines.append('<!-- URL userinfo was removed from artifact URLs/host fallback. '
                     'Verify candidate links are publicly accessible before publishing. -->')
        lines.append('')
    for name, pages in sections:
        lines.append(f"## {_metadata_text(name) or 'TODO: section name'}")
        lines.append("")
        for p in pages:
            title = _metadata_text(p["title"]) or _metadata_text(_slug_title(p["url"])) or "TODO: page title"
            desc = _metadata_text(p["description"])
            suffix = f": {desc}" if desc else ""
            lines.append(f"- [{title}]({_link_destination(p['url'])}){suffix}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _page_meta(url, allow_private, timeout):
    resp = http.fetch(url, allow_private=allow_private, timeout=timeout)
    if _metadata_problem(resp):
        return None
    doc = htmlx.parse(resp.text, base_url=resp.final_url or url)
    return {"url": resp.final_url or url, "title": doc.title or "",
            "description": (doc.meta_by_name("description")
                            or doc.meta_by_property("og:description") or "")}


def build(base: str, *, allow_private=False, timeout=20, max_pages=40,
          concurrency=4, obey_robots=True) -> dict:
    for name, value in (('max_pages', max_pages), ('concurrency', concurrency)):
        if type(value) is not int or value < 1:
            raise GenerationError(f'{name} must be a positive integer.')
    base = http.normalize_url(base)
    home = http.fetch(base, allow_private=allow_private, timeout=timeout)
    problem = _metadata_problem(home)
    if problem:
        raise GenerationError(f'Cannot generate llms.txt: homepage metadata is unavailable '
                              f'({problem}). No artifact was generated.')
    base = home.final_url or base
    parsed = urlparse(base)
    root = f"{parsed.scheme}://{parsed.netloc}"
    source_host = parsed.netloc
    host = source_host.rsplit('@', 1)[-1]
    authentication_removed = host != source_host
    hdoc = htmlx.parse(home.text, base_url=base)
    site_name = (hdoc.meta_by_property("og:site_name") or hdoc.title or host)
    description = (hdoc.meta_by_name("description")
                   or hdoc.meta_by_property("og:description") or "")

    robots_txt = http.fetch_text(urljoin(root + "/", "robots.txt"),
                                 allow_private=allow_private, timeout=timeout) or ""
    rt = RobotsTxt.parse(robots_txt)
    candidates = crawl_site.discover(base, allow_private=allow_private,
                                     timeout=timeout, limit=max_pages * 2,
                                     robots_txt=robots_txt)
    urls = []
    for u in candidates:
        if obey_robots and rt.disallowed(u, crawl_site.CRAWLER_AGENT):
            continue
        urls.append(u)
        if len(urls) >= max_pages:
            break

    with ThreadPoolExecutor(max_workers=concurrency) as ex:
        metas = [m for m in ex.map(
            lambda u: _page_meta(u, allow_private, timeout), urls) if m]

    # Drop per-page descriptions that just echo the site-wide description — that's
    # boilerplate, not useful per-link context.
    site_desc = description.strip().lower()
    for m in metas:
        artifact_url = _without_userinfo(m['url'])
        authentication_removed = authentication_removed or artifact_url != m['url']
        m['url'] = artifact_url
        if m["description"].strip().lower() == site_desc:
            m["description"] = ""

    coverage = {"basis": "selected_page_metadata_fetches_v1", "attempted_pages": len(urls),
                "included_pages": len(metas), "omitted_pages": len(urls) - len(metas)}
    if authentication_removed:
        coverage['authentication_removed'] = True
    return {"site_name": site_name, "description": description,
            "sections": group_sections(metas), "pages": len(metas), "coverage": coverage}


@url_errors
def main(argv=None) -> int:
    cfg = configlib.load_from_args(argv)
    d = cfg.defaults
    ap = argparse.ArgumentParser(description="Generate a starter llms.txt",
                                 parents=[configlib.config_arg_parser()])
    ap.add_argument("url", help="site URL")
    ap.add_argument("--max-pages", type=int, default=40,
                    help="positive maximum pages to include (default 40)")
    ap.add_argument("--concurrency", type=int, default=d["concurrency"],
                    help="positive number of concurrent page requests")
    ap.add_argument("--timeout", type=int, default=d["timeout"])
    ap.add_argument("--ignore-robots", action="store_true")
    ap.add_argument("--allow-private", action="store_true")
    ap.add_argument("-o", "--output")
    args = ap.parse_args(argv)

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

    try:
        data = build(args.url, allow_private=args.allow_private, timeout=args.timeout,
                     max_pages=args.max_pages, concurrency=args.concurrency,
                     obey_robots=not args.ignore_robots)
        out = render_llms_txt(data["site_name"], data["description"], data["sections"],
                              coverage=data.get('coverage'))
    except GenerationError as exc:
        print(f'Error: {exc}', file=sys.stderr)
        return 2
    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(out)
        print(f"Wrote llms.txt ({data['pages']} pages) to {args.output}")
    else:
        print(out)
    print("\n# NOTE: this is a starter — curate it, and treat llms.txt as a "
          "low-cost, low-certainty bet (see references/geo-llmo.md).",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
